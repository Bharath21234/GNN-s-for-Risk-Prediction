"""
Step 8: Auto-generate the paper's results macros and tables from results/*.csv.

Writes:
  paper/results_macros.tex  : \renewcommand macros for headline numbers
  paper/tables.tex          : LaTeX tabulars (forward losses, backtests,
                              sector DM, ablation, walk-forward)

Runs after step 5-7. Missing inputs degrade gracefully to a visible TODO so a
partial run still compiles. Numbers are reported exactly as computed.
"""

import os, sys, json
import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(__file__))
import config
R = config.RESULTS_DIR
P = "paper/"

# var_backtest.csv/es_backtest.csv are indexed by the lowercase model key
# (gnn, mlp, ...); forward_losses.csv (and hence `order`/`mdl` below) uses the
# display label (GNN, "MLP (no graph)", ...) -- map display label back to key.
_KEY_OF_LABEL = {"GNN": "gnn", "MLP (no graph)": "mlp", "GCN": "gcn",
                 "GARCH(1,1)": "garch", "GJR-GARCH": "gjr", "Historical Sim": "histsim",
                 "GNN+MLP Ensemble": "blend"}


def _read(fn, **kw):
    path = R + fn
    return pd.read_csv(path, **kw) if os.path.exists(path) else None


def _f(x, nd=4):
    try:
        return f"{float(x):.{nd}f}"
    except Exception:
        return "--"


def _p(x):
    # Self-contained math snippet including the relation symbol, so callers
    # always write "$p$\macro" (never "$p=\macro$") -- a macro's p-value can
    # cross the <0.001 threshold between reruns, and "$p=$<$0.001$" is broken
    # nested math mode. See dmGarchP/dmMlpP/main.tex usage.
    try:
        v = float(x)
        return "$<$0.001" if v < 1e-3 else f"$={v:.3f}$"
    except Exception:
        return "--"


def main():
    os.makedirs(P, exist_ok=True)
    macros, tables = [], []
    tables.append("% Auto-generated by 8_make_paper.py; do not edit by hand.\n")

    fl = _read("forward_losses.csv", index_col=0)
    dm = _read("dm_tests.csv")
    vb = _read("var_backtest.csv", index_col=0)
    eb = _read("es_backtest.csv", index_col=0)
    sec = _read("sector_forward_loss.csv", index_col=0)
    rec = _read("reconstruction_rmse.csv", index_col=0)
    abl = _read("ablation_graph.csv", index_col=0)
    wf = _read("walkforward.csv", index_col=0)
    sens = _read("sensitivity.csv")
    # 97.5% robustness table (first extra tail level, if present)
    rob, rob_pct = None, None
    for a in getattr(config, "EXTRA_TAIL_ALPHAS", []):
        cand = _read(f"robustness_a{round(a*1000):03d}.csv", index_col=0)
        if cand is not None:
            rob, rob_pct = cand, (1 - a) * 100
            break

    # ── Headline macros ────────────────────────────────────────────────────────
    def dm_lookup(sub):
        if dm is None:
            return None
        m = dm[dm["comparison"].str.contains(sub)]
        return m.iloc[0] if len(m) else None

    if fl is not None and "GNN" in fl.index:
        macros.append(r"\renewcommand{\gnnFZ}{%s}" % _f(fl.loc["GNN", "FZ0_mean"]))
        if "FZ0_ensemble" in fl.columns:
            macros.append(r"\renewcommand{\gnnFZEns}{%s}" % _f(fl.loc["GNN", "FZ0_ensemble"]))
            if "MLP (no graph)" in fl.index:
                macros.append(r"\renewcommand{\mlpFZEns}{%s}" % _f(fl.loc["MLP (no graph)", "FZ0_ensemble"]))
        if "GARCH(1,1)" in fl.index:
            macros.append(r"\renewcommand{\garchFZ}{%s}" % _f(fl.loc["GARCH(1,1)", "FZ0_mean"]))
    g = dm_lookup("GARCH"); m = dm_lookup("MLP")
    if g is not None:
        macros.append(r"\renewcommand{\dmGarchP}{%s}" % _p(g["p_value"]))
    if m is not None:
        macros.append(r"\renewcommand{\dmMlpP}{%s}" % _p(m["p_value"]))
    gc = dm_lookup("GCN"); gj = dm_lookup("GJR"); hs = dm_lookup("Historical")
    if gc is not None:
        macros.append(r"\renewcommand{\dmGcnP}{%s}" % _p(gc["p_value"]))
    if gj is not None:
        macros.append(r"\renewcommand{\dmGjrP}{%s}" % _p(gj["p_value"]))
    if hs is not None:
        macros.append(r"\renewcommand{\dmHistsimP}{%s}" % _p(hs["p_value"]))

    # ── Attention-dropout ablation macro (Section 4.1 / Results) ────────────────
    attn_path = R + "attn_dropout_ablation.json"
    if os.path.exists(attn_path):
        with open(attn_path) as f:
            attn = json.load(f)
        if "dm_vs_baseline_p" in attn:
            macros.append(r"\renewcommand{\attnVsBaseP}{%s}" % _p(attn["dm_vs_baseline_p"]))

    if sec is not None:
        fz_cols = [c for c in sec.columns if c.endswith("FZ0")]
        if {"GNN FZ0", "GARCH(1,1) FZ0"} <= set(sec.columns):
            wins = int((sec["GNN FZ0"] < sec["GARCH(1,1) FZ0"]).sum())
            macros.append(r"\renewcommand{\sectorWins}{%d/%d}" % (wins, len(sec)))

    # ── Ensemble-blend macros (Step 11: val-selected GNN+MLP convex blend) ──────
    eb_path = R + "ensemble_blend.json"
    if os.path.exists(eb_path):
        with open(eb_path) as f:
            blend_json = json.load(f)
        p0 = blend_json.get("primary", {})
        if p0:
            macros.append(r"\renewcommand{\blendW}{%s}" % _f(p0.get("w"), 2))
            macros.append(r"\renewcommand{\blendFZ}{%s}" % _f(p0.get("blend_test_FZ0")))
            macros.append(r"\renewcommand{\blendVsMlpP}{%s}" % _p(p0.get("dm_vs_mlp_p")))
            macros.append(r"\renewcommand{\blendVsGnnP}{%s}" % _p(p0.get("dm_vs_gnn_p")))
            macros.append(r"\renewcommand{\blendVsGarchP}{%s}" % _p(p0.get("dm_vs_garch_p")))
        pex = next((v for k, v in blend_json.items() if k != "primary"), {})
        if pex:
            macros.append(r"\renewcommand{\blendWtwo}{%s}" % _f(pex.get("w"), 2))
            macros.append(r"\renewcommand{\blendVsMlpPtwo}{%s}" % _p(pex.get("dm_vs_mlp_p")))
            macros.append(r"\renewcommand{\blendVsGarchPtwo}{%s}" % _p(pex.get("dm_vs_garch_p")))

    # ── Post-hoc scalar recalibration macros (Step 12) ──────────────────────────
    rc_path = R + "recalibration.json"
    if os.path.exists(rc_path):
        with open(rc_path) as f:
            rc = json.load(f)
        if "gnn" in rc:
            macros.append(r"\renewcommand{\recalGnnK}{%s}" % _f(rc["gnn"].get("k"), 2))
            macros.append(r"\renewcommand{\recalGnnFZ}{%s}" % _f(rc["gnn"].get("scaled_test_FZ0")))
            macros.append(r"\renewcommand{\recalGnnVsGarchP}{%s}" % _p(rc["gnn"].get("dm_vs_garch_p")))
            macros.append(r"\renewcommand{\recalGnnKupiec}{%s}" % _f(rc["gnn"].get("kupiec_pass_pct"), 1))
        if "mlp" in rc:
            macros.append(r"\renewcommand{\recalMlpK}{%s}" % _f(rc["mlp"].get("k"), 2))
            macros.append(r"\renewcommand{\recalMlpFZ}{%s}" % _f(rc["mlp"].get("scaled_test_FZ0")))
            macros.append(r"\renewcommand{\recalMlpVsGarchP}{%s}" % _p(rc["mlp"].get("dm_vs_garch_p")))
        if "blend" in rc:
            macros.append(r"\renewcommand{\recalBlendFZ}{%s}" % _f(rc["blend"].get("scaled_test_FZ0")))
            macros.append(r"\renewcommand{\recalBlendVsGarchP}{%s}" % _p(rc["blend"].get("dm_vs_garch_p")))
        if "dm_gnn_scaled_vs_mlp_scaled_p" in rc:
            macros.append(r"\renewcommand{\recalGnnVsMlpP}{%s}" % _p(rc["dm_gnn_scaled_vs_mlp_scaled_p"]))

    # ── Table 1: forward-looking losses + calibration ──────────────────────────
    if fl is not None:
        order = [x for x in ["GNN", "MLP (no graph)", "GNN+MLP Ensemble", "GCN",
                             "GARCH(1,1)", "GJR-GARCH", "Historical Sim"] if x in fl.index]
        has_ens = "FZ0_ensemble" in fl.columns
        _SHORT = {"MLP (no graph)": "MLP (no gr.)", "GARCH(1,1)": "GARCH",
                  "GJR-GARCH": "GJR", "Historical Sim": "HistSim",
                  "GNN+MLP Ensemble": "GNN+MLP"}
        header = (r"Model & FZ0 (seed) & FZ0 (ens.) & "
                  r"VaR viol.\,(\%) & Kupiec (\%) & ES $Z_2$ \\") if has_ens else \
                 r"Model & FZ0 & Pinball & VaR viol.\ (\%) & Kupiec pass (\%) & ES $Z_2$ \\"
        lines = [r"\begin{table}[h]\centering",
                 r"\caption{Forward-looking FZ0 (lower is better). "
                 r"``Per-seed'' is mean$\pm$std of each seed's independent loss; "
                 r"``ensemble'' averages the seeds' predictions before scoring "
                 r"(what the Diebold--Mariano tests and CIs below use). "
                 r"Best (per-seed) in \textbf{bold}. Pinball loss shown in "
                 r"Fig.~\ref{fig:forward}.}" if has_ens else
                 r"\caption{Forward-looking losses (lower is better), mean$\pm$std over seeds, "
                 r"with VaR/ES calibration. Best in \textbf{bold}.}",
                 r"\label{tab:main}"]
        if has_ens:
            lines += [r"\footnotesize", r"\setlength{\tabcolsep}{4pt}"]
        lines += [r"\begin{tabular}{l" + ("c" * (5 if has_ens else 5)) + r"}", r"\toprule",
                  header, r"\midrule"]
        best = fl.loc[order, "FZ0_mean"].astype(float).idxmin() if order else None
        for mdl in order:
            fz = _f(fl.loc[mdl, "FZ0_mean"], 4)
            sd = _f(fl.loc[mdl, "FZ0_std"], 4) if "FZ0_std" in fl.columns else "--"
            fzc = f"\\textbf{{{fz}}}$\\pm${sd}" if mdl == best else f"{fz}$\\pm${sd}"
            ens = _f(fl.loc[mdl, "FZ0_ensemble"], 4) if has_ens and mdl in fl.index else "--"
            pb = _f(fl.loc[mdl, "pinball_mean"], 5) if "pinball_mean" in fl.columns else "--"
            key = _KEY_OF_LABEL.get(mdl, mdl)
            viol = kup = z2 = "--"
            if vb is not None and key in vb.index:
                viol = _f(float(vb.loc[key, "mean_violation_rate"]) * 100, 2)
                kup = _f(vb.loc[key, "kupiec_pass_pct"], 1)
            if eb is not None and key in eb.index:
                z2 = _f(eb.loc[key, "z2"], 3)
            label = _SHORT.get(mdl, mdl) if has_ens else mdl
            if has_ens:
                lines.append(f"{label} & {fzc} & {ens} & {viol} & {kup} & {z2} \\\\")
            else:
                lines.append(f"{label} & {fzc} & {pb} & {viol} & {kup} & {z2} \\\\")
        lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
        tables += lines

    # ── Table 2: Diebold-Mariano (overall) ─────────────────────────────────────
    if dm is not None:
        lines = [r"\begin{table}[h]\centering",
                 r"\caption{Diebold--Mariano tests on FZ0 loss (HAC + HLN). "
                 r"Negative stat $\Rightarrow$ GNN lower loss.}", r"\label{tab:dm}",
                 r"\begin{tabular}{lccc}", r"\toprule",
                 r"Comparison & DM stat & $p$-value & mean diff \\", r"\midrule"]
        for _, r_ in dm.iterrows():
            lines.append(f"{r_['comparison']} & {_f(r_['dm_stat'],3)} & {_p(r_['p_value'])} & {_f(r_['mean_diff'],5)} \\\\")
        lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
        tables += lines

    # ── Table 3: sector FZ0 + per-sector DM ────────────────────────────────────
    if sec is not None and "GNN FZ0" in sec.columns:
        lines = [r"\begin{table}[h]\centering",
                 r"\caption{Sector-level FZ0 loss and per-sector Diebold--Mariano "
                 r"(GNN vs.\ GARCH).}", r"\label{tab:sector}",
                 r"\begin{tabular}{lccccc}", r"\toprule",
                 r"Sector & $n$ & GNN & GARCH & DM & $p$ \\", r"\midrule"]
        for s, r_ in sec.iterrows():
            n = int(r_["n_stocks"]) if "n_stocks" in sec.columns else "--"
            dmv = _f(r_["DM vs GARCH"], 2) if "DM vs GARCH" in sec.columns else "--"
            pv = _p(r_["p vs GARCH"]) if "p vs GARCH" in sec.columns else "--"
            lines.append(f"{s} & {n} & {_f(r_['GNN FZ0'],4)} & {_f(r_['GARCH(1,1) FZ0'],4)} & {dmv} & {pv} \\\\")
        lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
        tables += lines

    # ── Table 4: graph-construction / edge-weight ablation ─────────────────────
    if abl is not None:
        lines = [r"\begin{table}[h]\centering",
                 r"\caption{Graph-construction and edge-weight ablation (test FZ0). "
                 r"All rows GraphSAGE except where noted; the GAT row includes the "
                 r"adopted attention dropout ($=0.3$), so it is not a clean rerun of "
                 r"the attention-dropout-free aggregation-rule comparison in "
                 r"Section~4.1.}",
                 r"\label{tab:ablation}", r"\begin{tabular}{lcc}", r"\toprule",
                 r"Configuration & edges & FZ0 \\", r"\midrule"]
        for c, r_ in abl.iterrows():
            ne = int(r_["n_edges"]) if "n_edges" in abl.columns else "--"
            sd = _f(r_["FZ0_std"], 4) if "FZ0_std" in abl.columns else "--"
            lines.append(f"{c} & {ne} & {_f(r_['FZ0_mean'],4)}$\\pm${sd} \\\\")
        lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
        tables += lines

    # ── Table 5: walk-forward ──────────────────────────────────────────────────
    if wf is not None:
        lines = [r"\begin{table}[h]\centering",
                 r"\caption{Rolling-origin (walk-forward) FZ0 by test year.}",
                 r"\label{tab:wf}", r"\begin{tabular}{lccc}", r"\toprule",
                 r"Test year & GNN & MLP & GARCH \\", r"\midrule"]
        for yr, r_ in wf.iterrows():
            lines.append(f"{yr} & {_f(r_.get('gnn_FZ0'),4)} & {_f(r_.get('mlp_FZ0'),4)} & {_f(r_.get('garch_FZ0'),4)} \\\\")
        lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
        tables += lines

    # ── Table 6: robustness at the extra (97.5%) tail level ────────────────────
    if rob is not None:
        lines = [r"\begin{table}[h]\centering",
                 r"\caption{Robustness at the %.1f\%% ES level: forward FZ0, "
                 r"Diebold--Mariano vs.\ GNN, and VaR coverage.}" % rob_pct,
                 r"\label{tab:robust}", r"\begin{tabular}{lcccc}", r"\toprule",
                 r"Model & FZ0 & DM vs GNN & $p$ & VaR viol.\ (\%) \\", r"\midrule"]
        for mdl, r_ in rob.iterrows():
            dmv = _f(r_.get("DM_vs_GNN"), 2) if not pd.isna(r_.get("DM_vs_GNN")) else "--"
            pv = _p(r_.get("p_vs_GNN")) if not pd.isna(r_.get("p_vs_GNN")) else "--"
            lines.append(f"{mdl} & {_f(r_['FZ0'],4)} & {dmv} & {pv} & "
                         f"{_f(r_['viol_rate_%'],2)} \\\\")
        lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
        tables += lines

    # ── Table 7: graph-hyperparameter sensitivity ──────────────────────────────
    if sens is not None:
        spread = float(sens["test_FZ0_mean"].max() - sens["test_FZ0_mean"].min())
        macros.append(r"\renewcommand{\sensSpread}{%s}" % _f(spread, 4))
        lines = [r"\begin{table}[h]\centering",
                 r"\caption{Graph-hyperparameter sensitivity: test FZ0 across the "
                 r"correlation-threshold $\times$ update-frequency grid "
                 r"(FZ0 spread $=%s$).}" % _f(spread, 4),
                 r"\label{tab:sens}", r"\begin{tabular}{lccc}", r"\toprule",
                 r"Corr.\ thresh. & Update freq. & edges & test FZ0 \\", r"\midrule"]
        for _, r_ in sens.iterrows():
            star = r"\,$\star$" if bool(r_.get("is_default")) else ""
            sd = _f(r_["test_FZ0_std"], 4) if "test_FZ0_std" in sens.columns else "--"
            lines.append(f"{_f(r_['corr_threshold'],2)}{star} & {int(r_['update_freq'])} & "
                         f"{int(r_['n_edges'])} & {_f(r_['test_FZ0_mean'],4)}$\\pm${sd} \\\\")
        lines += [r"\bottomrule", r"\end{tabular}",
                  r"\\[2pt]{\footnotesize $\star$ = default configuration.}",
                  r"\end{table}", ""]
        tables += lines

    if not macros:
        macros = ["% no results yet; macros keep their placeholder TODO values"]

    with open(P + "results_macros.tex", "w") as f:
        f.write("\n".join(macros) + "\n")
    with open(P + "tables.tex", "w") as f:
        f.write("\n".join(tables) + "\n")
    print(f"Wrote {P}results_macros.tex ({len(macros)} macros) and {P}tables.tex "
          f"({sum(t.strip().startswith(chr(92)+'begin{table}') for t in tables)} tables).")


if __name__ == "__main__":
    main()
